import mongoose from "mongoose";

const contactsSchema = new mongoose.Schema({
    userId: {
        type: mongoose.Schema.Types.ObjectId,
        ref: 'User',
        required: true,
    },
    name: {
        type: String,
        required: true,
    },
    phoneNumber : {
        type: String,
        required: true,
    },
    email: {
        type: String,
        required: false,
    },
    isFavourite: {
        type: Boolean,
        default: false,
    },
    contactType: {
        type: String,
        enum: ['work', 'home', 'personal'],
        required: true,
        default: 'personal',
    }, 
    photo:{
        type: String,
    }

}, {
    timestamps: true,
    versionKey: false,
    });


export const Contact = mongoose.model('Contact', contactsSchema);